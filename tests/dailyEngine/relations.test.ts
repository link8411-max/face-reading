test('모르는 글자는 예외', () => {
  expect(() => 천간관계판정('x', '갑')).toThrow('모르는 천간: x')
  expect(() => 천간관계판정('갑', '자')).toThrow('모르는 천간: 자')
  expect(() => 지지관계판정('자', 'x')).toThrow('모르는 지지: x')
  expect(() => 지지관계판정('갑', '자')).toThrow('모르는 지지: 갑')
  expect(() => 오행관계판정('x', '목')).toThrow('모르는 오행: x')
  expect(() => 오행관계판정('목', '갑')).toThrow('모르는 오행: 갑')
})
