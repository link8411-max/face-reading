import { box, circlePts, type Pt } from './brush'
import type { ElKey, Wish } from './keys'

export interface TStroke {
  pts: Pt[]
  /** 붓 굵기(시안 굵기 × 1.75 반영) */
  w: number
  start: number
  end: number
}

const WS = 1.75
const S = (pts: Pt[], w: number, start: number, end: number): TStroke => ({ pts, w: w * WS, start, end })
const PI = Math.PI

