export function birthYears(slug: ZodiacSlug): number[] {
  const idx = ZODIAC_SLUGS.indexOf(slug)
  const years: number[] = []
  for (let y = 1924; y <= 2026; y++) if ((((y - 4) % 12) + 12) % 12 === idx) years.push(y)
  return years
}

