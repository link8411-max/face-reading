const 쌍찾기 = (쌍들: string[], a: string, b: string) => 쌍들.find((p) => p.includes(a) && p.includes(b)) ?? `${a}${b}`
const 묶음찾기 = (묶음들: string[], a: string, b: string) => 묶음들.find((p) => p.includes(a) && p.includes(b)) ?? `${a}${b}`


// 조사만 돌려준다(받침은 바로 앞 글자 기준: '경(금)'은 괄호 안 '금')
const 조사 = (w: string, withB: string, without: string) => josa(w, withB, without).slice(w.length)

