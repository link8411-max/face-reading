// 이달의 운세: 데이터의 달과 현재 달이 같을 때만 보여 준다 (지난달 운세 노출 방지)
export function monthlyFor(type: MbtiType, now: Date): MbtiProfile['monthly'] | null {
  const m = mbtiProfiles[type].monthly
  const current = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}`
  return m.month === current ? m : null
}

// 유형 페이지에 실제로 보이는 본문 전체 (분량 기준 검사용, 궁합 섹션 문장 포함)
export function pageText(type: MbtiType): string {
  const p = mbtiProfiles[type]
  const best = bestMatches(type, 'love').map((b) => {
    const s = compatSummary(type, b)
    return `${b} ${s.label} ${s.lines.join(' ')}`
  })
  const others = (['friend', 'work'] as const).flatMap((ctx) => bestMatches(type, ctx).map((b) => `${b} ${compatSummary(type, b).lines[0]}`))
  return [
    p.summary, ...p.strengths, p.love,
    ...p.travel.domestic.map((t) => `${t.place} ${t.why}`), ...p.travel.abroad.map((t) => `${t.place} ${t.why}`),
    ...p.jobs.map((j) => `${j.title} ${j.why}`), p.workStyle, p.monthly.text, ...best, ...others,
  ].join(' ')
}

